/**
 * URBANDIRECT — Authoritative Global Location Database
 * 
 * Provides ISO 3166-1 alpha-2 countries, administrative divisions (states/provinces/prefectures/regions),
 * and curated cities/towns with normalized canonical identifiers.
 */

export interface CountryDef {
  code: string; // ISO 3166-1 alpha-2
  name: string;
  regionLabel: string;
  districtLabel: string;
  postalLabel: string;
  currencyCode: string;
}

export interface RegionDef {
  code: string;
  name: string;
  countryCode: string;
  regionType: string;
}

export interface DistrictDef {
  code: string;
  name: string;
  stateRegion: string;
  countryCode: string;
  districtType?: string;
}

export interface CityDef {
  cityId: string;
  cityName: string;
  stateRegion: string;
  country: string;
  countryCode: string;
  district?: string;
  postalCode?: string;
  postalCodePrefix?: string;
  localityType?: 'CITY' | 'TOWN' | 'VILLAGE' | 'LOCALITY';
  populationTier?: 'METRO_MEGACITY' | 'LARGE_CITY' | 'MEDIUM_CITY' | 'TOWN' | 'VILLAGE';
  locationSource?: 'VERIFIED_DIRECTORY' | 'GEOCODED' | 'USER_PROVIDED';
  defaultLocality: string;
  coordinates?: { lat: number; lng: number };
}


